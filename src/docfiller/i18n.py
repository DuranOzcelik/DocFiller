CATALOGUES: dict[str, dict[str, str]] = {"tr": TURKISH}

_current = DEFAULT


def available() -> dict[str, str]:
    return dict(LANGUAGES)


def current() -> str:
    return _current


def set_language(code: str) -> None:
    global _current
    _current = code if code in LANGUAGES else DEFAULT


def tr(text: str, **fields: Any) -> str:
    """Translate `text` into the active language and fill any ``{placeholders}``.

    Formatting happens after lookup so translators keep the placeholders without
    having to repeat the English wording around them.
    """
    translated = CATALOGUES.get(_current, {}).get(text, text)
    if fields:
        try:
            return translated.format(**fields)
        except (KeyError, IndexError):
            # A translation with a mistyped placeholder must not crash the UI.
            return text.format(**fields)
    return translated


def missing_keys() -> dict[str, list[str]]:
    """Which English strings each catalogue has yet to translate.

    Used by the test suite so an untranslated string is noticed during
    development rather than by a user.
    """
    known = set(TURKISH)
    return {code: sorted(known - set(catalogue)) for code, catalogue in CATALOGUES.items()}
